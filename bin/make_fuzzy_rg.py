"""Write an OCR-tolerant ripgrep pattern file from the strict keywords and a generic OCR confusion table.

Usage: python -I bin/make_fuzzy_rg.py OUT.rg
Each letter becomes a class of its common OCR shape confusions, with one optional stray punctuation mark
or broken hyphenation allowed between letters. Built from the table only, not from any labeled article.
"""
import sys

# Shape confusions only; v1 also swapped vowels and allowed spaces between letters, which matched
# "entere(d)", "out of a" and similar thousands of times in 1859 text, so v2 drops both.
CONFUSE = {
    "a": "a@4", "b": "bh6", "c": "ce(", "e": "ec3", "g": "gq9", "h": "hb", "i": "il1!|",
    "l": "l1i!|", "n": "nu", "o": "o0cQ", "p": "p", "r": "rt", "s": "s5$", "t": "tf1",
    "u": "uvn",
}
GAP = r"(?:[^\sA-Za-z0-9]|-\s)?"   # one stray punctuation mark, or a broken hyphenation "- "
KEYWORDS = ["aurora", "borealis", "northern light", "polar light"]


def fuzzy(word):
    parts = []
    for ch in word:
        if ch == " ":
            parts.append(r"\W{1,3}")
        else:
            parts.append("[" + "".join(sorted(set(CONFUSE.get(ch, ch)))).replace("\\", "\\\\").replace("]", "\\]") + "]")
    return r"\b" + GAP.join(parts)


with open(sys.argv[1], "w") as out:
    out.write("# OCR-tolerant variants of the strict keywords, generated by bin/make_fuzzy_rg.py.\n")
    for k in KEYWORDS:
        out.write(fuzzy(k) + "\n")
